use frontseat_plugin::prelude::*;
use frontseat_plugin::repository::{beneath, join, resolve};
use serde::de::IgnoredAny;
use serde::Deserialize;
use std::collections::BTreeMap;
use std::path::{Component, Path};

#[derive(Deserialize)]
struct Workspace {
    version: String,
    #[serde(default)]
    deps: Vec<String>,
    #[serde(default)]
    modules: Vec<Module>,
    #[serde(default)]
    plugins: Vec<IgnoredAny>,
}

#[derive(Deserialize)]
struct Module {
    path: String,
}

#[derive(Deserialize)]
struct Generation {
    version: String,
    plugins: Vec<Generator>,
    #[serde(default)]
    inputs: Vec<GenerationInput>,
}

/// What a template generates from: a directory of the workspace.
#[derive(Deserialize)]
struct GenerationInput {
    directory: String,
    #[serde(flatten)]
    options: BTreeMap<String, IgnoredAny>,
}

#[derive(Deserialize)]
struct Generator {
    local: Option<String>,
    out: String,
    #[serde(flatten)]
    options: BTreeMap<String, IgnoredAny>,
}

/// Where one output of a template goes in the source.
pub(super) enum Place {
    /// Beneath the Buf workspace, relative to it.
    Directory(String),
    /// Outside the Buf workspace, relative to the repository.
    Destination(String),
}

pub(super) struct Output {
    /// Where the action leaves it, relative to the Buf workspace.
    pub path: String,
    pub place: Place,
    pub patterns: Vec<String>,
}

/// One generation template, `buf.gen.yaml` or `buf.gen.<name>.yaml`, and
/// the action that generates from it.
pub(super) struct Template {
    /// Its file name, in the Buf workspace.
    pub file: String,
    /// The action's name: `generate`, or `generate-<name>`.
    pub action: String,
    /// The directory buf is told to write beneath (`-o`), relative to the
    /// Buf workspace; none where every output is beneath the workspace.
    pub base: Option<String>,
    pub tools: Vec<String>,
    pub outputs: Vec<Output>,
}

pub(super) struct Manifest {
    pub templates: Vec<Template>,
}

/// What a workspace says that is valid and not built yet.
fn not_served(what: &str, path: &str, message: &str) -> Error {
    Error::not_served(what, message)
        .at(path)
        .help("Use repository-local modules and pinned local Go generators.")
}

fn invalid(path: &str, message: impl Into<String>) -> Error {
    Error::invalid(
        "invalid-manifest",
        path,
        message,
        "Use a Buf v2 workspace and pinned local Go generators.",
    )
}

/// The action a template's file is generated by: `buf.gen.yaml` by
/// `generate`, `buf.gen.<name>.yaml` by `generate-<name>`, its name being
/// lower-case letters, digits and dashes.
fn action_of(file: &str) -> Option<String> {
    if file == "buf.gen.yaml" {
        return Some("generate".into());
    }
    let name = file.strip_prefix("buf.gen.")?.strip_suffix(".yaml")?;
    let named = name
        .bytes()
        .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
        && name
            .bytes()
            .next()
            .is_some_and(|b| b.is_ascii_lowercase() || b.is_ascii_digit());
    named.then(|| format!("generate-{name}"))
}

pub(super) fn read(repo: &Repository, root: &str) -> Result<Option<Manifest>, Error> {
    let path = join(root, "buf.yaml");
    let Some(workspace) = repo.yaml_document::<Workspace>(&path)? else {
        return Ok(None);
    };
    if workspace.version != "v2" {
        return Err(invalid(&path, "this Buf workspace must use v2"));
    }
    if !workspace.deps.is_empty() {
        return Err(not_served(
            "dependencies",
            &path,
            "a Buf workspace that depends on a module of the Buf Schema Registry is not built yet",
        ));
    }
    if !workspace.plugins.is_empty() {
        return Err(not_served(
            "check-plugins",
            &path,
            "a Buf workspace's check plugins are not run yet",
        ));
    }
    if workspace
        .modules
        .iter()
        .any(|module| !local_directory(&module.path))
    {
        return Err(invalid(
            &path,
            "module paths must stay inside this Buf workspace",
        ));
    }
    let files = repo.glob(root, &["buf.gen.yaml", "buf.gen.*.yaml"])?;
    let mut templates = Vec::with_capacity(files.len());
    for path in files {
        let file = path.rsplit('/').next().unwrap_or(&path).to_string();
        let Some(action) = action_of(&file) else {
            return Err(invalid(
                &path,
                "a generation template is named buf.gen.yaml or buf.gen.<name>.yaml, its name lower-case letters, digits and dashes",
            ));
        };
        if let Some(template) = template(repo, root, &path, file, action)? {
            templates.push(template);
        }
    }
    Ok(Some(Manifest { templates }))
}

fn template(
    repo: &Repository,
    root: &str,
    path: &str,
    file: String,
    action: String,
) -> Result<Option<Template>, Error> {
    let Some(generation) = repo.yaml_document::<Generation>(path)? else {
        return Ok(None);
    };
    if generation.version != "v2" || generation.plugins.is_empty() {
        return Err(invalid(
            path,
            "generation must use v2 and declare at least one plugin",
        ));
    }
    for input in generation.inputs {
        if !local_directory(&input.directory)
            || input.options.keys().any(|key| {
                !["types", "exclude_types", "paths", "exclude_paths"].contains(&key.as_str())
            })
        {
            return Err(invalid(
                path,
                "generation inputs must be directories inside this Buf workspace",
            ));
        }
    }
    let mut result = Template {
        base: None,
        tools: vec!["buf".into()],
        outputs: vec![],
        file,
        action,
    };
    // Each output where the repository has it, and where it is in the
    // workspace when it is there.
    let mut placed = Vec::with_capacity(generation.plugins.len());
    for generator in generation.plugins {
        if generator.options.contains_key("remote") {
            return Err(not_served(
                "remote-generators",
                path,
                "a generator of the Buf Schema Registry is not run yet",
            ));
        }
        if generator.options.keys().any(|key| {
            ![
                "opt",
                "include_imports",
                "include_wkt",
                "strategy",
                "types",
                "exclude_types",
            ]
            .contains(&key.as_str())
        }) {
            return Err(invalid(
                path,
                "only pinned local generators and their native options are supported",
            ));
        }
        let archive = matches!(
            Path::new(&generator.out)
                .extension()
                .and_then(|s| s.to_str()),
            Some("zip" | "jar")
        );
        if archive || generator.out.is_empty() || generator.out.contains(['\\', '\0']) {
            return Err(invalid(
                path,
                "generator outputs must be directories, not archives",
            ));
        }
        // The directory as the host names an output: plainly, so that
        // "./gen/go" and "gen/go" are one place. Neither the workspace
        // nor the repository is an output.
        let Some(at) = resolve(root, &generator.out) else {
            return Err(invalid(
                path,
                format!(
                    "generator output {} is outside the repository",
                    generator.out
                ),
            ));
        };
        let place = match beneath(root, &at) {
            Some(directory) => Place::Directory(directory.into()),
            None if at.is_empty() || at == root => {
                return Err(invalid(
                    path,
                    format!(
                        "generator output {} is the whole of a directory that holds more than it",
                        generator.out
                    ),
                ))
            }
            None => Place::Destination(at.clone()),
        };
        let (tool, pattern) = match generator.local.as_deref() {
            Some("protoc-gen-go") => ("protoc-gen-go", "**/*.pb.go"),
            Some("protoc-gen-connect-go") => ("protoc-gen-connect-go", "**/*.connect.go"),
            _ => {
                return Err(invalid(
                    path,
                    "generation requires a local protoc-gen-go or protoc-gen-connect-go",
                ))
            }
        };
        if !result.tools.iter().any(|name| name == tool) {
            result.tools.push(tool.into());
        }
        // protogen emits an adjacent .go.meta file for annotate_code=true.
        // It belongs to this producer too; consumer input sets still decide
        // whether they need that metadata or only the generated Go source.
        let patterns = if tool == "protoc-gen-go" {
            vec![pattern, "**/*.pb.go.meta"]
        } else {
            vec![pattern]
        };
        placed.push((at, place, patterns));
    }
    // An output outside the workspace is written by buf beneath a
    // directory of the workspace's own, at where it is in the repository,
    // so that the action writes nothing outside its project: told
    // `-o .gen-sdk/api`, buf writes `../sdk/go/api` at
    // `.gen-sdk/sdk/go/api`. The host places it where the template says.
    let apart = placed
        .iter()
        .any(|(_, place, _)| matches!(place, Place::Destination(_)))
        .then(|| match result.action.strip_prefix("generate-") {
            Some(name) => format!(".gen-{name}"),
            None => ".gen".into(),
        });
    result.base = apart.as_deref().map(|apart| join(apart, root));
    for (at, place, patterns) in placed {
        // A destination is written apart, so where nothing is, each is a
        // directory of the workspace.
        let left = match (&apart, &place) {
            (Some(apart), _) => join(apart, &at),
            (None, Place::Directory(directory) | Place::Destination(directory)) => {
                directory.clone()
            }
        };
        if let Some(output) = result.outputs.iter_mut().find(|output| output.path == left) {
            for pattern in patterns {
                if !output.patterns.iter().any(|p| p == pattern) {
                    output.patterns.push(pattern.into());
                }
            }
        } else {
            result.outputs.push(Output {
                path: left,
                place,
                patterns: patterns.into_iter().map(String::from).collect(),
            });
        }
    }
    Ok(Some(result))
}

// Buf's directory input is literal, not a glob. The standard path library
// rejects absolute paths and traversal; the host validates declared outputs
// again and confines every source read and action on the worker.
fn local_directory(value: &str) -> bool {
    !value.is_empty()
        && !value.contains(['\\', '\0'])
        && Path::new(value)
            .components()
            .all(|part| matches!(part, Component::Normal(_) | Component::CurDir))
}

#[cfg(test)]
mod place_tests {
    use super::action_of;
    use frontseat_plugin::repository::resolve;

    #[test]
    fn an_output_is_where_the_repository_has_it_whatever_its_spelling() {
        for spelled in ["gen/go", "./gen/go", "gen//go/", "gen/./go", "x/../gen/go"] {
            assert_eq!(
                resolve("api", spelled).as_deref(),
                Some("api/gen/go"),
                "{spelled}"
            );
        }
        assert_eq!(resolve("api", "../lib/gen").as_deref(), Some("lib/gen"));
        assert_eq!(
            resolve("proto/api", "../../lib/gen").as_deref(),
            Some("lib/gen")
        );
        for outside in ["../../outside", "/abs/gen", "../x/../../y"] {
            assert_eq!(resolve("api", outside), None, "{outside}");
        }
        assert_eq!(resolve("", "../gen"), None);
    }

    #[test]
    fn a_template_is_generated_by_the_action_its_name_gives() {
        assert_eq!(action_of("buf.gen.yaml").as_deref(), Some("generate"));
        assert_eq!(
            action_of("buf.gen.sdk.yaml").as_deref(),
            Some("generate-sdk")
        );
        assert_eq!(
            action_of("buf.gen.daemon-2.yaml").as_deref(),
            Some("generate-daemon-2")
        );
        for refused in [
            "buf.gen..yaml",
            "buf.gen.Sdk.yaml",
            "buf.gen.a.b.yaml",
            "buf.gen.-x.yaml",
            "buf.gen.x_y.yaml",
        ] {
            assert_eq!(action_of(refused), None, "{refused}");
        }
    }
}

#[cfg(test)]
mod served_tests {
    use frontseat_plugin::prelude::*;
    use frontseat_plugin_test::{Files, TestHost, TestPlugin};

    /// What a Buf workspace says that is valid and not built yet is
    /// refused as not served, each by its own reason, and a file that is
    /// wrong is refused as invalid; the control is a workspace of local
    /// modules and local generators, which is built.
    #[test]
    fn what_a_workspace_says_that_is_not_built_yet_is_refused_as_not_served() {
        let plugin = TestPlugin::new(crate::served());
        let context = plugin.context(Profile::Development);
        let analyze = |files: Files| plugin.analyze(&TestHost::new(files), &context, &["proto"]);
        let workspace = |buf: &str| Files::new().with("proto/buf.yaml", buf);
        let generating = |generator: &str| {
            workspace("version: v2\n").with(
                "proto/buf.gen.yaml",
                format!("version: v2\nplugins:\n  - {generator}\n"),
            )
        };
        analyze(generating("local: protoc-gen-go\n    out: gen")).answered();
        for (files, reason) in [
            (
                workspace("version: v2\ndeps: [buf.build/x/y]\n"),
                "dependencies-not-served",
            ),
            (
                workspace("version: v2\nplugins: [{plugin: buf-plugin-x}]\n"),
                "check-plugins-not-served",
            ),
            (
                generating("remote: buf.build/protocolbuffers/go\n    out: gen"),
                "remote-generators-not-served",
            ),
        ] {
            assert_eq!(analyze(files).refused(reason).code, Code::Unimplemented);
        }
        analyze(workspace("version: v1\n")).refused("invalid-manifest");
    }
}
