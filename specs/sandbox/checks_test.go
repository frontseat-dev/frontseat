// A fix runs where the checkout is, which is in the daemon's sandbox and
// nowhere else: in the daemon's sandbox, with the
// workers' own tool brought from the grid by its digest, never on the
// grid. The sandbox is the workers' platform, so the tool the check runs
// with on the grid is the tool the fix runs with here. A run asked to fix
// formats the checkout and the check then passes over it; one not asked
// to fix fails the check and writes nothing.
// Fixes in sandboxes / A run asked to fix runs gofmt where the checkout is, with the grid's tool, and writes the checkout.
func TestARunAskedToFixRunsGofmtWhereTheCheckoutIsWithTheGridSToolAndWritesTheCheckout(t *testing.T) {
	spec := newScenario(t)

	checkout := spec.aRepository()
	const unformatted = "package main\n\nimport \"fmt\"\n\nfunc main() {\nfmt.Println(  \"hello\" )\n}\n"
	formatted, err := format.Source([]byte(unformatted))
	spec.Expect(err).NotTo(HaveOccurred())
	testfiles.Tree(spec.TB, checkout, map[string]string{
		"hello/go.mod":  "module example.com/hello\n\ngo 1.27\n",
		"hello/main.go": unformatted,
	})
	testpins.Go(spec.TB, checkout)
	workspace := spec.inASandboxOfItsOwn(spec.cloning(checkout))

	actions := workspace.checkedThenFixed("//code/hello:go.format", code+"/hello/main.go", unformatted)
	var applied []string
	for _, action := range actions.GetActions() {
		for _, rewrite := range action.GetRewrites() {
			if rewrite.GetApplied() {
				applied = append(applied, rewrite.GetLocation().GetPath())
			}
		}
	}
	spec.Expect(applied).To(ConsistOf("hello/main.go"))
	spec.Expect(workspace.holds(code + "/hello/main.go")).To(Equal(string(formatted)))
}

// Fixes in sandboxes / A run asked to fix runs cargo fmt where the checkout is, under the workspace manifest written for it.
func TestARunAskedToFixRunsCargoFmtWhereTheCheckoutIsUnderTheWorkspaceManifestWrittenForIt(t *testing.T) {
	spec := newScenario(t)

	checkout := spec.aRepository()
	const unformatted = "fn main() {\nprintln!(\"{}\",   1);\n}\n"
	const formatted = "fn main() {\n    println!(\"{}\", 1);\n}\n"
	testfiles.Tree(spec.TB, checkout, map[string]string{
		"Cargo.toml":      "[workspace]\nresolver = \"2\"\nmembers = [\"app\"]\n",
		"Cargo.lock":      "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\n",
		"app/Cargo.toml":  "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
		"app/src/main.rs": unformatted,
		"frontseat.yaml":  "plugins:\n  cargo: {}\n",
	})
	testpins.Own(spec.TB, checkout)
	workspace := spec.inASandboxOfItsOwn(spec.cloning(checkout))
	workspace.checkedThenFixed("//code/app:cargo.format", code+"/app/src/main.rs", unformatted)
	spec.Expect(workspace.holds(code + "/app/src/main.rs")).To(Equal(formatted))
	spec.Expect(workspace.holds(code+"/Cargo.toml")).To(Equal("[workspace]\nresolver = \"2\"\nmembers = [\"app\"]\n"), "the workspace manifest written for the fix reached the checkout")
}
