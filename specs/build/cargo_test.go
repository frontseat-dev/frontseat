// Cargo packages / A change to the source fetches nothing again.
func TestAChangeToTheSourceFetchesNothingAgain(t *testing.T) {
	t.Parallel()
	spec := newScenario(t)

	workspace := spec.cargoWorkspace()
	before := workspace.build()
	workspace.write("hello/src/main.rs", "fn main() {\n    println!(\"{}!\", greet::greeting(2));\n}")
	after := workspace.build()
	spec.Expect(after.outcome()).To(Equal("SUCCESS"), after.diagnostics())
	for _, fetch := range spec.crates(before) {
		spec.Expect(after.action(fetch)).To(Equal(before.action(fetch)), fetch)
		spec.Expect(after.cameFrom(fetch)).To(Equal("grid_cache"), fetch)
	}
}

// Cargo packages / A crate that is not what the lock says is not kept, and nothing is built with it; the other crates are as they were.
func TestACrateThatIsNotWhatTheLockSaysIsNotKeptAndNothingIsBuiltWithItTheOtherCratesAreAsTheyWere(t *testing.T) {
	t.Parallel()
	spec := newScenario(t)

	cfgIf := crateOf("cfg-if@1.0.0")
	itoa := crateOf("itoa@1.0.18")

	workspace := spec.cargoWorkspace()
	before := workspace.build()
	workspace.write("Cargo.lock", strings.Replace(workspace.file("Cargo.lock"), "baf1de4339761588bc0619e3cbc0120ee582ebb74b53b4efbf79117bd2da40fd", "baf1de4339761588bc0619e3cbc0120ee582ebb74b53b4efbf79117bd2da40f0", 1))
	after := workspace.build()
	spec.Expect(after.outcome()).NotTo(Equal("SUCCESS"))
	spec.Expect(after.outcomeOf(cfgIf)).To(Equal("error"))
	spec.Expect(after.result(cfgIf).GetMessage()).To(ContainSubstring("checksum"))
	spec.Expect(after.outcomeOf("//hello:cargo.compile")).To(Equal("skipped"))
	// itoa, which did not change, is as it was, and greet builds.
	spec.Expect(after.action(itoa)).To(Equal(before.action(itoa)))
	spec.Expect(after.cameFrom(itoa)).To(Equal("grid_cache"))
	spec.Expect(after.outcomeOf("//greet:cargo.compile")).To(Equal("passed"))
}

// Cargo packages / A crate two repositories lock alike is downloaded once, for both.
func TestACrateTwoRepositoriesLockAlikeIsDownloadedOnceForBoth(t *testing.T) {
	spec := newScenario(t)

	// The crates are this spec's own origin's, which counts how often
	// each is asked of it, and the daemons are told to fetch them there.
	// Two repositories, each with a daemon of its own, lock the same two
	// crates: the second asks for neither, whatever the first had to,
	// since the grid's asset service kept what it fetched.
	origin := testorigin.Crates(spec.TB)
	spec.rewrites = origin.Rewrites()
	first := spec.cargoWorkspace()
	spec.Expect(first.build().outcome()).To(Equal("SUCCESS"))
	itoaAsked, cfgIfAsked := origin.Asked("itoa", "1.0.18"), origin.Asked("cfg-if", "1.0.0")
	second := spec.cargoWorkspace()
	spec.Expect(second.build().outcome()).To(Equal("SUCCESS"))
	spec.Expect(origin.Asked("itoa", "1.0.18")).To(Equal(itoaAsked))
	spec.Expect(origin.Asked("cfg-if", "1.0.0")).To(Equal(cfgIfAsked))
	// The control: a crate that is not what its lock says is asked of
	// the origin each time, since the service keeps nothing of it.
	third := spec.cargoWorkspace()
	third.write("Cargo.lock", strings.Replace(third.file("Cargo.lock"), "baf1de4339761588bc0619e3cbc0120ee582ebb74b53b4efbf79117bd2da40fd", "baf1de4339761588bc0619e3cbc0120ee582ebb74b53b4efbf79117bd2da40f1", 1))
	spec.Expect(third.build().outcome()).NotTo(Equal("SUCCESS"))
	spec.Expect(origin.Asked("cfg-if", "1.0.0")).To(Equal(cfgIfAsked + 1))
	spec.Expect(origin.Asked("itoa", "1.0.18")).To(Equal(itoaAsked))
}

// Cargo packages / What clippy finds is reported with its file and line, and fails the lint.
func TestWhatClippyFindsIsReportedWithItsFileAndLineAndFailsTheLint(t *testing.T) {
	t.Parallel()
	spec := newScenario(t)

	workspace := spec.cargoWorkspace()
	workspace.write("hello/src/main.rs", "fn main() {\n    let x = 1;\n    println!(\"{}\", greet::greeting(1));\n}\n")
	built := workspace.build(of("//hello:cargo.lint"))
	spec.Expect(built.outcomeOf("//hello:cargo.lint")).To(Equal("failed"))
	found := built.diagnosticsOf("//hello:cargo.lint")
	spec.Expect(found).NotTo(BeEmpty())
	spec.Expect(found[0].GetRuleId()).To(Equal("cargo/clippy"))
	spec.Expect(found[0].GetSourceLocation().GetPath()).To(Equal("hello/src/main.rs"))
	spec.Expect(found[0].GetSourceLocation().GetLine()).To(BeEquivalentTo(2))
}

// Cargo packages / A package rustfmt would change fails its format check, names the file, and is left as it was.
func TestAPackageRustfmtWouldChangeFailsItsFormatCheckNamesTheFileAndIsLeftAsItWas(t *testing.T) {
	t.Parallel()
	spec := newScenario(t)

	workspace := spec.cargoWorkspace()
	const unformatted = "fn main() {\nprintln!(\"{}\",   greet::greeting(1));\n}\n"
	workspace.write("hello/src/main.rs", unformatted)
	built := workspace.build(of("//hello:cargo.format"))
	spec.Expect(built.outcomeOf("//hello:cargo.format")).To(Equal("failed"))
	found := built.diagnosticsOf("//hello:cargo.format")
	spec.Expect(found).To(HaveLen(1))
	spec.Expect(found[0].GetRuleId()).To(Equal("cargo/format"))
	spec.Expect(found[0].GetSourceLocation().GetPath()).To(Equal("hello/src/main.rs"))
	spec.Expect(workspace.file("hello/src/main.rs")).To(Equal(unformatted[:len(unformatted)-1]))
}

// Cargo packages / A library built as a dynamic library is also built for wasm32-wasip1 where the repository pins its standard library.
func TestALibraryBuiltAsADynamicLibraryIsAlsoBuiltForWasm32Wasip1WhereTheRepositoryPinsItsStandardLibrary(t *testing.T) {
	t.Parallel()
	spec := newScenario(t)

	workspace := spec.cargoWorkspace()
	workspace.write("Cargo.toml", "[workspace]\nresolver = \"2\"\nmembers = [\"greet\", \"hello\", \"module\"]\n\n[workspace.package]\nedition = \"2021\"\nversion = \"0.1.0\"\n\n[workspace.dependencies]\nitoa = \"1\"\n")
	workspace.write("module/Cargo.toml", "[package]\nname = \"my-module\"\nedition.workspace = true\nversion.workspace = true\n\n[lib]\ncrate-type = [\"cdylib\"]\n\n[dependencies]\ngreet = { path = \"../greet\" }\n")
	workspace.write("module/src/lib.rs", "#[no_mangle]\npub extern \"C\" fn greet_len() -> u32 {\n    greet::greeting(1).len() as u32\n}\n")
	workspace.write("Cargo.lock", workspace.file("Cargo.lock")+"\n[[package]]\nname = \"my-module\"\nversion = \"0.1.0\"\ndependencies = [\n \"greet\",\n]\n")
	built := workspace.build(of("//module:cargo.wasm"))
	spec.Expect(built.outcome()).To(Equal("SUCCESS"), built.diagnostics())
	spec.Expect(built.outcomeOf("//module:cargo.wasm")).To(Equal("passed"))
}

// crateOf is the label of the shared fetch of a crate: name@version.
func crateOf(c string) string { return "//:cargo.fetch/" + c }

// crates are the build's fetches of crates.
func (spec *scenario) crates(b *Build) []string {
	spec.Helper()
	var out []string
	for _, label := range b.actions() {
		if strings.Contains(label, ":cargo.fetch/") {
			out = append(out, label)
		}
	}
	return out
}
