// A Cargo workspace is many packages sharing one lock. Each package is a
// project of its own, requiring the packages it depends on by path; the
// workspace's root is no project. cargo runs in the package's directory
// and walks up to the workspace root, which is written for it narrowed
// to the packages present, with the lock as it is in the repository.
//
// Crates come from the lock alone. cargo cannot fetch one crate by
// itself, so each crate of crates.io a package depends on is a shared
// fetch of its own that runs no tool: the daemon asks the grid's asset
// service for the crate's archive by its URL and the lock's sha256, the
// service fetches it once through the proxy, checks the sha256 before it
// keeps anything, and keeps it by URL and checksum for every repository
// and daemon of the grid; the fetch unpacks it into cargo's home with no
// network, beside the checksum file cargo's directory source reads. The
// actions that build read the crates from there, offline, and cargo
// checks each against the lock again. A change to one crate of the lock
// fetches that crate again and no other, a change to the source fetches
// nothing, two packages that lock a crate alike share its fetch, and two
// repositories that do share its download. A crate that is not what the
// lock says is not kept, and nothing is built with it. A lock with a
// crate from a git repository or another registry is fetched whole by
// cargo, as before.
// Cargo packages / A Cargo workspace's packages are projects, each requiring the packages it depends on by path.
func TestACargoWorkspaceSPackagesAreProjectsEachRequiringThePackagesItDependsOnByPath(t *testing.T) {
	t.Parallel()
	spec := newScenario(t)

	workspace := spec.cargoWorkspace()
	spec.Expect(rootsOf(workspace.projects())).To(ConsistOf("greet", "hello"))
	spec.Expect(workspace.requires("/hello")).To(Equal([]Requirement{{
		what:       "cargo:greet",
		saidAt:     "hello/Cargo.toml:7",
		at:         "0.1.0",
		providedBy: "greet",
	}}))
	spec.Expect(workspace.requires("/greet")).To(BeEmpty())
}

// Cargo packages / A single Cargo package at a repository's root is one project.
func TestASingleCargoPackageAtARepositorySRootIsOneProject(t *testing.T) {
	t.Parallel()
	spec := newScenario(t)

	workspace := spec.cargoWorkspace()
	for _, gone := range []string{"Cargo.toml", "Cargo.lock", "greet", "hello"} {
		spec.Expect(os.RemoveAll(filepath.Join(workspace.directory, gone))).To(Succeed())
	}
	workspace.write("Cargo.toml", "[package]\nname = \"solo\"\nversion = \"0.1.0\"\nedition = \"2021\"\n")
	workspace.write("Cargo.lock", "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"solo\"\nversion = \"0.1.0\"\n")
	workspace.write("src/main.rs", "fn main() {}\n")
	spec.Expect(rootsOf(workspace.projects())).To(ConsistOf(""))
}

