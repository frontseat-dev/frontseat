package stack

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// The container is pointed at its own resolver, and the resolver at the
// nameservers the runtime gave it, what else the runtime said kept; a
// container started again, which holds what init wrote before, is left as
// it is. The controls are a resolv.conf that names no nameserver at all,
// and one that names one that is no address, which are refused.
func TestInitHasTheContainerAskItsOwnResolver(t *testing.T) {
	dir := t.TempDir()
	r := Resolver{Config: filepath.Join(dir, "resolv.conf"), Forward: filepath.Join(dir, "unbound", "forward.conf"), Listen: "127.0.0.1"}
	write := func(content string) {
		t.Helper()
		if err := os.WriteFile(r.Config, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	read := func(path string) string {
		t.Helper()
		raw, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		return string(raw)
	}

	write("# Generated by Docker Engine.\nnameserver 0.250.250.200\nnameserver 192.168.65.7\nsearch lan\noptions ndots:0\n")
	if err := r.write(); err != nil {
		t.Fatal(err)
	}
	config := read(r.Config)
	if !strings.Contains(config, "\nnameserver 127.0.0.1\n") || strings.Contains(config, "0.250.250.200") || !strings.Contains(config, "search lan\n") || !strings.Contains(config, "options ndots:0\n") {
		t.Errorf("the container's resolv.conf is\n%s", config)
	}
	forward := read(r.Forward)
	if !strings.Contains(forward, "forward-zone:") || !strings.Contains(forward, "forward-addr: 0.250.250.200\n") || !strings.Contains(forward, "forward-addr: 192.168.65.7\n") {
		t.Errorf("the resolver asks\n%s", forward)
	}

	// Started again: what init wrote is what it finds.
	if err := r.write(); err != nil {
		t.Fatalf("started again: %v", err)
	}
	if read(r.Config) != config || read(r.Forward) != forward {
		t.Error("started again, init changed what it wrote before")
	}

	write("# nothing here\n")
	if err := r.write(); err == nil || !strings.Contains(err.Error(), "no nameserver") {
		t.Errorf("the control: a resolv.conf naming no nameserver was taken: %v", err)
	}
	// A nameserver said with a comment after it is read as resolv.conf
	// reads it, one of IPv6 as one of IPv4, and one on the container's
	// loopback but not at the resolver's own address is asked as any
	// other: what init wrote is known by its header, not by the address.
	write("nameserver 10.0.0.2 # the runtime's\nnameserver fd00::53\nnameserver 127.0.0.53\n")
	if err := r.write(); err != nil {
		t.Fatal(err)
	}
	if forward := read(r.Forward); !strings.Contains(forward, "forward-addr: 10.0.0.2\n") || !strings.Contains(forward, "forward-addr: fd00::53\n") || !strings.Contains(forward, "forward-addr: 127.0.0.53\n") {
		t.Errorf("the resolver asks\n%s", forward)
	}
	// The resolver's own address, given by the runtime, would have it ask
	// itself; an address with a zone, or with a port read after it, is
	// not an address alone.
	for refused, why := range map[string]string{
		"127.0.0.1":        "ask itself",
		"::ffff:127.0.0.1": "ask itself",
		"0.0.0.0":          "ask itself",
		"fe80::1%eth0":     "no nameserver",
		"fe80::1%x@5353":   "no nameserver",
	} {
		write("nameserver " + refused + "\n")
		if err := r.write(); err == nil || !strings.Contains(err.Error(), why) {
			t.Errorf("a nameserver %s alone was taken, or refused for another reason: %v", refused, err)
		}
	}
	// One of a link's own beside another is passed by, and the other asked.
	write("nameserver fe80::1%eth0\nnameserver 10.0.0.9\n")
	if err := r.write(); err != nil {
		t.Fatalf("a link's own nameserver beside another stopped the container: %v", err)
	}
	if forward := read(r.Forward); strings.Contains(forward, "fe80") || !strings.Contains(forward, "forward-addr: 10.0.0.9\n") {
		t.Errorf("the resolver asks\n%s", forward)
	}
	write(resolverHeader + "nameserver 127.0.0.1\n")
	if err := os.Remove(r.Forward); err != nil {
		t.Fatal(err)
	}
	if err := r.write(); err == nil || !strings.Contains(err.Error(), "is gone") {
		t.Errorf("the control: init's own resolv.conf with nowhere for its resolver to ask was taken: %v", err)
	}
	write("nameserver not-an-address\n")
	if err := r.write(); err == nil || !strings.Contains(err.Error(), "no address") {
		t.Errorf("the control: a nameserver that is no address was taken: %v", err)
	}
}
