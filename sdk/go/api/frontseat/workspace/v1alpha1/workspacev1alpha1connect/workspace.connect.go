// frontseat.workspace.v1alpha1: workspaces. A workspace is a working area
// of repositories joined into one graph, for a person, an agent or a job.
// It lives in a sandbox, which is its isolation and knows nothing of it,
// and a daemon there holds its source and builds it: one workspace and
// one daemon in a sandbox, which this API has no way to say otherwise.
//
// The control plane alone serves this service, and is the one writer of
// what a workspace is asked for: it makes a sandbox for a new one, tells
// the daemon there what to hold and reads back what it holds, ends one,
// and leads to each one's build API and shell by its name, and to
// nothing else of it. A workspace is changed from outside it: inside its
// sandbox its source is fixed, and the command line there asks its
// daemon's build API alone.
//
// Every call to a control plane is a person's, known by the token they
// present as a bearer token. A call that presents none is refused
// UNAUTHENTICATED with the reason IDENTITY_MISSING, and one whose token
// the control plane does not know with IDENTITY_INVALID, each in
// ErrorInfo of the domain workspace.frontseat.dev; the ways to a
// workspace's build API and shell are held alike. A workspace is its
// owner's, who asked for it first: another who names it is refused
// PERMISSION_DENIED with the reason NOT_OWNER, and is listed none of
// another's. What this service refuses by name carries ErrorInfo of the
// domain workspace.frontseat.dev, with the reason each call names. A
// call to a workspace's build API that is none of its calls is refused
// UNIMPLEMENTED with the reason CALL_NOT_LED.
//
// A workspace is kept as what was asked for, its spec, and what is so,
// its status. A call writes the spec and returns; the control plane then
// works until the status says the same, and goes on from the spec after
// it or the daemon was stopped: a daemon started again is told again.

