package config

import (
	"github.com/frontseat-dev/frontseat/server/internal/model"
	"path"
	"path/filepath"
	"slices"
	"strings"

	"github.com/frontseat-dev/frontseat/sdk/go/entity"
	"go.yaml.in/yaml/v4"
)

// Generated is a Component's consent that another Component generates one
// of its directories: spec.frontseat.generated in its catalog file, one
// entry of the list.
//
//	spec:
//	  frontseat:
//	    generated:
//	      - directory: gen        # relative to this catalog file
//	        by: component:api     # the Component whose project generates it
//
// A generator writes into a directory outside its own project only where
// the Component that owns the directory says so: the generator's own
// template says where it writes, and this says the Component it writes
// into lets it. Only a Component says it, and only of a Component.
type Generated struct {
	// Repository is the repository it is written in; File the catalog
	// file, relative to it.
	Repository, File string
	// Directory is the directory, relative to the repository.
	Directory string
	// Entity is the Component that says it; By the Component it says
	// generates the directory.
	Entity, By entity.Ref
}

// Generated returns what the repository's Components say other Components
// generate of their directories, in the order their files give it.
func (r *Repository) Generated() []Generated { return r.generated }

// readGenerated reads spec.frontseat.generated of one catalog document.
func readGenerated(file place, directory string, component entity.Ref, node *yaml.Node) ([]Generated, error) {
	wrong := func(line int, format string, args ...any) ([]Generated, error) {
		return nil, file.at(line, format, args...)
	}
	if err := componentOnly(component, node, "spec.frontseat.generated"); err != nil {
		return nil, file.in(err)
	}
	var err error
	if node.Kind != yaml.SequenceNode || len(node.Content) == 0 {
		return wrong(node.Line, "spec.frontseat.generated is a list, each entry a directory and the Component that generates it (by)")
	}
	out := make([]Generated, 0, len(node.Content))
	for _, entry := range node.Content {
		if entry.Kind != yaml.MappingNode {
			return wrong(entry.Line, "an entry of spec.frontseat.generated is a map of directory and by")
		}
		said := Generated{Repository: file.repository, File: file.file, Entity: component}
		var by, at *yaml.Node
		for i := 0; i+1 < len(entry.Content); i += 2 {
			key, value := entry.Content[i], entry.Content[i+1]
			if value.Kind != yaml.ScalarNode || value.ShortTag() != "!!str" {
				return wrong(value.Line, "generated %s is text", key.Value)
			}
			switch key.Value {
			case "directory":
				at = value
			case "by":
				by = value
			default:
				return nil, &model.Mistake{Repository: file.repository, File: file.file, Line: key.Line, Message: "an entry of spec.frontseat.generated takes no key " + key.Value, Help: "it takes directory and by"}
			}
		}
		if at == nil || by == nil {
			return wrong(entry.Line, "an entry of spec.frontseat.generated says both the directory and the Component that generates it (by)")
		}
		// A directory of the Component's own, written plainly beneath its
		// catalog file: whether no other Component owns it is the
		// evaluation's to hold, which knows where each is.
		written := at.Value
		if written == "" || strings.HasPrefix(written, "/") || !filepath.IsLocal(filepath.FromSlash(written)) || written == "." || path.Clean(written) != written || strings.ContainsAny(written, "\\\x00") || slices.Contains(strings.Split(written, "/"), ".frontseat") {
			return wrong(at.Line, "generated directory is not a directory beneath this catalog file, written plainly")
		}
		said.Directory = path.Join(directory, written)
		if said.By, err = entity.ParseIn(by.Value, component.Namespace); err != nil {
			return wrong(by.Line, "generated by names no entity: a reference is a name, kind:name or kind:namespace/name, each of letters and digits, with dashes, dots or underscores between them")
		}
		if said.By.Kind != entity.KindComponent {
			return wrong(by.Line, "generated by names what is no Component: only a Component is said to generate a directory, the one whose project generates it")
		}
		out = append(out, said)
	}
	return out, nil
}
