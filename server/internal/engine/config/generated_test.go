package config_test

import (
	"strings"
	"testing"

	"github.com/frontseat-dev/frontseat/server/internal/engine/config"
)

func consentCatalog(kind, body string) files {
	return files{
		"frontseat.yaml":        "plugins: {}\n",
		"lib/catalog-info.yaml": "apiVersion: backstage.io/v1alpha1\nkind: " + kind + "\nmetadata: {name: lib}\nspec:\n  frontseat:\n    generated:\n" + body,
	}
}

// A Component says which Component generates a directory of its own, by
// the directory beneath its catalog file and the Component's reference;
// a System is neither the one that says it nor the one said to generate.
func TestAComponentSaysWhichComponentGeneratesItsDirectory(t *testing.T) {
	read, err := config.Read(t.Context(), "repo", consentCatalog("Component", "      - directory: gen\n        by: component:api\n      - {directory: other/gen, by: tools}\n"))
	if err != nil {
		t.Fatal(err)
	}
	got := read.Generated()
	if len(got) != 2 || got[0].Directory != "lib/gen" || got[0].File != "repo/lib/catalog-info.yaml" || got[0].Entity.String() != "component:default/lib" || got[0].By.String() != "component:default/api" || got[1].Directory != "lib/other/gen" || got[1].By.String() != "component:default/tools" {
		t.Fatalf("consent lost its directory or Components: %+v", got)
	}
	for body, says := range map[string]string{
		"      - directory: gen\n        by: system:api\n":                                                         "generated by names what is no Component: only a Component is said to generate a directory",
		"      - directory: gen\n        by: resource:api\n":                                                       "only a Component",
		"      - directory: gen\n        by: 'component:'\n":                                                       "names no entity",
		"      - directory: gen\n":                                                                                 "says both the directory and the Component",
		"      - by: component:api\n":                                                                              "says both the directory and the Component",
		"      - directory: gen\n        by: [component:api]\n":                                                    "generated by is text",
		"      - directory: ../app\n        by: component:api\n":                                                   "not a directory beneath this catalog file",
		"      - directory: /abs\n        by: component:api\n":                                                     "not a directory beneath this catalog file",
		"      - directory: .\n        by: component:api\n":                                                        "not a directory beneath this catalog file",
		"      - directory: gen/\n        by: component:api\n":                                                     "not a directory beneath this catalog file",
		"      - directory: .frontseat\n        by: component:api\n":                                               "not a directory beneath this catalog file",
		"      - directory: gen\n        by: component:api\n        also: x\n":                                     "takes no key also",
		"      - directory: gen\n        by: component:api\n      - directory: gen\n        by: component:other\n": "said to be generated twice",
		"      directory: gen\n":                                                                                   "is a list",
		"      []\n":                                                                                               "is a list",
		"      - gen\n":                                                                                            "is a map of directory and by",
	} {
		if _, err := config.Read(t.Context(), "repo", consentCatalog("Component", body)); err == nil || !strings.Contains(err.Error(), "lib/catalog-info.yaml") || !strings.Contains(err.Error(), says) {
			t.Errorf("%q: got %v, want it refused at its file saying %q", body, err, says)
		}
	}
	// What names no entity is not repeated: the refusal says what a
	// reference is written as. The control is the same Component named.
	for by, refused := range map[string]bool{"component:default/secret value": true, "component:default/api": false} {
		_, err := config.Read(t.Context(), "repo", consentCatalog("Component", "      - directory: gen\n        by: '"+by+"'\n"))
		if refused != (err != nil) || err != nil && (strings.Contains(err.Error(), "secret") || !strings.Contains(err.Error(), "generated by names no entity: a reference is")) {
			t.Errorf("by %q: %v", by, err)
		}
	}
	for _, kind := range []string{"System", "Domain", "Resource", "API"} {
		if _, err := config.Read(t.Context(), "repo", consentCatalog(kind, "      - directory: gen\n        by: component:api\n")); err == nil || !strings.Contains(err.Error(), "spec.frontseat.generated belongs to a Component") {
			t.Errorf("a %s consented: %v", kind, err)
		}
	}
}
