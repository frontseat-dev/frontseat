// redirected answers as the plugins do, but for Buf's analysis, whose every
// destination it moves to another place: a plugin's answer claiming a
// destination no Component let it have.
type redirected struct {
	asking
	to string
}

func (r redirected) askObserved(ctx context.Context, plugin *pluginhost.Plugin, view repositoryView, method string, request, response proto.Message) (bool, []pluginhost.Read, error) {
	again, reads, err := r.asking.askObserved(ctx, plugin, view, method, request, response)
	if answer, ok := response.(*pluginv1.AnalyzeResponse); ok && err == nil && plugin.Description.GetName() == "buf" {
		for _, analysis := range answer.GetAnalyses() {
			for _, project := range analysis.GetProjects() {
				for _, generated := range project.GetGeneratedSources() {
					if generated.GetDestination() == "" {
						continue
					}
					// "./x" names a directory of the producer's project.
					if within, ok := strings.CutPrefix(r.to, "./"); ok {
						generated.Destination, generated.Directory = "", within
					} else {
						generated.Destination = r.to
					}
				}
			}
		}
	}
	return again, reads, err
}

// A generator writes into a directory outside its project only where the
// Component that owns it says so, naming the generator's Component: each
// other case is refused by name before anything is bound, beside the
// consented control, which binds the claim beneath lib's module root.
func TestAGeneratedDestinationNeedsTheConsentOfItsComponent(t *testing.T) {
	r := newReadiness(t, t.TempDir(), "go", "buf", "backstage")
	testforge.GeneratedElsewhere(t, r.root)
	retainedWrite(t, r.root, "app/catalog-info.yaml", testforge.ConsentingComponent("app", ""))
	evaluated := func(answers asking) (Evaluation, error) {
		return evaluate(t.Context(), retainedTake(t, &source.Keeper{}, r.root), r.plugins, answers, typev1.Profile_PROFILE_DEVELOPMENT, nil)
	}
	consented, err := evaluated(&Answers{})
	if err != nil {
		t.Fatalf("a consented destination was refused, so this test proves nothing: %v", err)
	}
	lib := readinessAction(t, consented.Actions, "//lib:go.compile")
	if len(lib.Artifacts) != 1 || lib.Artifacts[0].Within != "gen" || lib.Artifacts[0].Source.Directory != "lib/gen" || lib.Artifacts[0].Source.Producer.String() != "//api:buf.generate-lib" {
		t.Fatalf("lib's module is bound %+v", lib.Artifacts)
	}
	for _, c := range []struct {
		name, file, content, says string
	}{
		{"no consent", "lib/catalog-info.yaml", testforge.ConsentingComponent("lib", ""), "//api:buf.generate-lib generates lib/gen, outside its own Component, and component:default/lib does not say that component:default/api generates it"},
		{"consent naming another Component", "lib/catalog-info.yaml", testforge.ConsentingComponent("lib", "    generated:\n      - directory: gen\n        by: component:app\n"), "component:default/lib does not say that component:default/api generates it"},
		{"consent of another directory", "lib/catalog-info.yaml", testforge.ConsentingComponent("lib", "    generated:\n      - directory: other\n        by: component:api\n"), "component:default/lib does not say that component:default/api generates it"},
		{"consent naming a System", "lib/catalog-info.yaml", testforge.ConsentingComponent("lib", "    generated:\n      - directory: gen\n        by: system:api\n"), "lib/catalog-info.yaml: line 11: generated by names system:default/api, and only a Component is said to generate a directory"},
		{"consent written by a System", "lib/catalog-info.yaml", strings.Replace(testforge.ConsentingComponent("lib", "    generated:\n      - directory: gen\n        by: component:api\n"), "kind: Component", "kind: System", 1), "spec.frontseat.generated belongs to a Component"},
		{"consent escaping its directory", "lib/catalog-info.yaml", testforge.ConsentingComponent("lib", "    generated:\n      - directory: ../app\n        by: component:api\n"), "is not a directory beneath this catalog file"},
		{"consent of a nested Component's directory", "lib/gen/catalog-info.yaml", testforge.ConsentingComponent("gen", ""), "component:default/lib says that component:default/api generates lib/gen, which is not its own directory but component:default/gen's"},
		{"consent of a directory holding a nested Component", "lib/gen/inner/catalog-info.yaml", testforge.ConsentingComponent("inner", ""), "//api:buf.generate-lib generates lib/gen, which holds component:default/inner at lib/gen/inner"},
		{"the producer in no Component", "api/catalog-info.yaml", "", "its project belongs to no Component"},
	} {
		t.Run(c.name, func(t *testing.T) {
			at := filepath.Join(r.root, filepath.FromSlash(c.file))
			was, err := os.ReadFile(at)
			if err != nil && !os.IsNotExist(err) {
				t.Fatal(err)
			}
			defer func() {
				if was == nil {
					_ = os.Remove(at)
					return
				}
				retainedWrite(t, r.root, c.file, string(was))
			}()
			if c.content == "" {
				if err := os.Remove(at); err != nil {
					t.Fatal(err)
				}
			} else {
				retainedWrite(t, r.root, c.file, c.content)
			}
			if _, err := evaluated(&Answers{}); err == nil || !strings.Contains(err.Error(), c.says) {
				t.Fatalf("got %v, want it refused saying %q", err, c.says)
			}
		})
	}
	if _, err := evaluated(&Answers{}); err != nil {
		t.Fatalf("the fixture was not restored: %v", err)
	}
	// What a plugin answers cannot take another directory than the one
	// consented: lib says api generates lib/gen, and a destination of
	// app/gen, beneath app's module root, is refused, naming app.
	if _, err := evaluated(redirected{asking: &Answers{}, to: "app/gen"}); err == nil || !strings.Contains(err.Error(), "//api:buf.generate-lib generates app/gen, outside its own Component, and component:default/app does not say") {
		t.Fatalf("a destination the plugin answered and no Component consented was not refused: %v", err)
	}
	// ...nor a directory no Component owns.
	if err := os.Remove(filepath.Join(r.root, "app", "catalog-info.yaml")); err != nil {
		t.Fatal(err)
	}
	if _, err := evaluated(redirected{asking: &Answers{}, to: "app/gen"}); err == nil || !strings.Contains(err.Error(), "which no Component owns to say it may") {
		t.Fatalf("a destination in no Component was not refused: %v", err)
	}
	// The same redirection to where lib consented is the control.
	if _, err := evaluated(redirected{asking: &Answers{}, to: "lib/gen"}); err != nil {
		t.Fatalf("control: %v", err)
	}
	// Within its own project, a generator needs no consent of its own
	// Component, and does of another Component nested in the project.
	retainedWrite(t, r.root, "api/sub/go.mod", "module example.com/sub\n\ngo 1.27\n")
	if _, err := evaluated(redirected{asking: &Answers{}, to: "./sub/gen"}); err != nil {
		t.Fatalf("a claim in the producer's own project and Component was refused: %v", err)
	}
	retainedWrite(t, r.root, "api/sub/catalog-info.yaml", testforge.ConsentingComponent("sub", ""))
	if _, err := evaluated(redirected{asking: &Answers{}, to: "./sub/gen"}); err == nil || !strings.Contains(err.Error(), "//api:buf.generate-lib generates api/sub/gen, outside its own Component, and component:default/sub does not say that component:default/api generates it") {
		t.Fatalf("a claim in a Component nested in the producer's project was not refused: %v", err)
	}
	retainedWrite(t, r.root, "api/sub/catalog-info.yaml", testforge.ConsentingComponent("sub", "    generated:\n      - directory: gen\n        by: component:api\n"))
	if _, err := evaluated(redirected{asking: &Answers{}, to: "./sub/gen"}); err != nil {
		t.Fatalf("the nested Component's consent control: %v", err)
	}
}

// A claim of the whole primary repository, which a plugin at its root may
// answer as directory ".", holds every Component but the root's, and is
// refused for them; with no Component beneath it, it is admitted.
func TestAClaimOfTheWholeRepositoryHoldsEveryNestedComponent(t *testing.T) {
	root := entity.New("", "", "root")
	claim := plan.GeneratedSource{ProjectRoot: "", Directory: ".", Patterns: []string{"**/*.pb.go"}, Producer: model.Label{Plugin: "x", Name: "generate"}}
	alone := Evaluation{Generated: []plan.GeneratedSource{claim}, Entities: []record.Located{{Ref: root}}}
	if err := consented(alone, nil); err != nil {
		t.Fatalf("control: %v", err)
	}
	nested := alone
	nested.Entities = append(nested.Entities, record.Located{Ref: entity.New("", "", "server"), Root: "server"})
	if err := consented(nested, nil); err == nil || !strings.Contains(err.Error(), "holds component:default/server at server") {
		t.Fatalf("a claim of the whole repository over a nested Component: %v", err)
	}
}
